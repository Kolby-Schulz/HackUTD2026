import { describe, expect, it } from 'vitest';
import { dbId, genNote, nodeOf, pendingText, screenState, slotsJson, withGenerated } from './live.ts';
import type { JobRec, Recs, VariantRec } from './live.ts';

const SLOTS = ['nav', 'hero', 'cta'];
const T = '2026-11-08T10:00:00.000Z';
const variant = (over: Partial<VariantRec>): VariantRec => ({
  id: 'landing/gen-1', screen: 'landing', parent: 'landing/b-calm', kind: 'child', author: 'variant-mac', model: 'nemotron',
  status: 'ready', tokens: 12300, costUsd: 0.04, durationMs: 41000, commit: 'abcdef1234', createdAt: T, ...over,
});
const job = (over: Partial<JobRec>): JobRec => ({ id: 1n, screen: 'landing', brief: 'Rounder buttons', model: '', status: 'done', createdAt: T, ...over });
const empty: Recs = { variants: [], mixes: [], picks: [], votes: [], jobs: [] };

describe('ids', () => {
  it('scopes node ids by screen', () => {
    expect(dbId('landing', 'a-bold')).toBe('landing/a-bold');
    expect(nodeOf('landing', 'landing/a-bold')).toBe('a-bold');
    expect(nodeOf('landing', 'pricing/a-bold')).toBeNull();
    expect(nodeOf('landing', 'landing/../x')).toBeNull();
    expect(nodeOf('landing', undefined)).toBeNull();
  });

  it('round-trips a mix slot map', () => {
    const json = slotsJson('landing', { nav: 'a-bold', hero: 'b-calm' });
    expect(JSON.parse(json)).toEqual({ nav: 'landing/a-bold', hero: 'landing/b-calm' });
    const s = screenState('landing', SLOTS, { ...empty, mixes: [{ id: 'landing/mix-1', screen: 'landing', title: '', note: ' ', slotsJson: json, author: 'ab', createdAt: T }] }, undefined);
    expect(s.combos).toEqual([{ id: 'mix-1', screen: 'landing', title: 'mix-1', parents: ['a-bold', 'b-calm'], picks: { nav: 'a-bold', hero: 'b-calm' }, createdAt: T }]);
  });
});

describe('screen state', () => {
  const recs: Recs = {
    variants: [variant({}), variant({ id: 'landing/mix-1', kind: 'mix' }), variant({ id: 'pricing/x', screen: 'pricing' })],
    mixes: [
      { id: 'landing/mix-1', screen: 'landing', title: 'Bold nav', note: 'why', slotsJson: '{"nav":"landing/a-bold","bogus":"landing/b","cta":"pricing/x"}', author: 'ab', createdAt: T },
      { id: 'landing/mix-2', screen: 'landing', title: 'Broken', note: '', slotsJson: '{not json', author: 'ab', createdAt: T },
    ],
    picks: [{ screen: 'landing', nodeId: 'landing/mix-1', by: 'ab' }, { screen: 'pricing', nodeId: 'pricing/x', by: 'ab' }],
    votes: [
      { screen: 'landing', nodeId: 'landing/a-bold', voter: 'me' },
      { screen: 'landing', nodeId: 'landing/a-bold', voter: 'you' },
      { screen: 'landing', nodeId: 'landing/b-calm', voter: 'them' },
    ],
    jobs: [job({ id: 1n, variantId: 'landing/gen-1' }), job({ id: 2n, status: 'queued' }), job({ id: 3n, screen: 'pricing' })],
  };
  const s = screenState('landing', SLOTS, recs, 'me');

  it('keeps only this screen and valid slots', () => {
    expect(s.combos.map((c) => [c.id, c.title, c.note, c.picks])).toEqual([['mix-1', 'Bold nav', 'why', { nav: 'a-bold' }], ['mix-2', 'Broken', undefined, {}]]);
    expect(s.final).toBe('mix-1');
    expect(s.jobs.map((j) => j.id)).toEqual([2n, 1n]);
  });

  it('counts votes and finds mine', () => {
    expect([...s.votes]).toEqual([['a-bold', 2], ['b-calm', 1]]);
    expect(s.myVote).toBe('a-bold');
    expect(screenState('landing', SLOTS, recs, undefined).myVote).toBeUndefined();
  });

  it('lists generated variants, not mixes, with their brief', () => {
    expect([...s.generated.keys()]).toEqual(['gen-1']);
    expect(s.generated.get('gen-1')).toMatchObject({ parent: 'b-calm', status: 'ready', brief: 'Rounder buttons' });
  });
});

describe('generated variants in the graph', () => {
  const gen = (status: VariantRec['status'], over: Partial<VariantRec> = {}) =>
    screenState('landing', SLOTS, { ...empty, variants: [variant({ status, ...over })], jobs: [job({ variantId: 'landing/gen-1', error: status === 'failed' ? 'tsc failed' : undefined })] }, undefined).generated;

  it('adds agent stats to a variant whose code is in the build', () => {
    const [info] = withGenerated([{ id: 'gen-1', title: 'Rounder', own: ['cta'], extends: 'b-calm' }], gen('ready'));
    expect(info).toMatchObject({ title: 'Rounder', own: ['cta'], note: 'Generated by variant-mac with nemotron · 12.3k tokens · $0.04 · 41 s' });
    expect(info.pending).toBeUndefined();
  });

  it('shows a placeholder until the code arrives', () => {
    const [ready] = withGenerated([], gen('ready'));
    expect(ready).toMatchObject({ id: 'gen-1', title: 'Rounder buttons', extends: 'b-calm', own: [], status: 'ready' });
    expect(ready.pending).toMatch(/commit abcdef1/);
    expect(withGenerated([], gen('generating'))[0].pending).toBe('variant-mac is writing this variant…');
    expect(withGenerated([], gen('failed'))[0].pending).toBe('Generation failed: tsc failed');
  });

  it('formats notes without empty stats', () => {
    const g = gen('generating', { tokens: 0, costUsd: 0, durationMs: 0, model: '' }).get('gen-1')!;
    expect(genNote(g)).toBe('Generated by variant-mac');
    expect(pendingText({ ...g, status: 'failed' })).toBe('Generation failed');
  });
});
